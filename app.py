
import streamlit as st
import pandas as pd
import joblib

# Page configuration
st.set_page_config(
    page_title="Airbnb Listing Price Analyzer",
    page_icon="🏠",
    layout="wide"
)

# Load the trained model pipeline
@st.cache_resource
def load_model():
    return joblib.load("random_forest_model.pkl")

try:
    model = load_model()
except FileNotFoundError:
    st.error(
        "Model file not found. Please save random_forest_model.pkl "
        "in the same folder as app.py."
    )
    st.stop()

# Website heading
st.title("🏠 Airbnb Listing Price Analyzer")
st.write(
    "Explore Airbnb listing prices and estimate a listing's price "
    "using your trained Random Forest model."
)

st.divider()

# Sidebar
st.sidebar.header("About This Project")
st.sidebar.write(
    "This project uses data analysis and machine learning "
    "to understand and predict Airbnb listing prices."
)
st.sidebar.write("Models evaluated: Linear Regression and Random Forest")

# Input form
st.header("🔮 Predict a Listing Price")
st.write("Enter the details of a new listing below.")

with st.form("prediction_form"):
    col1, col2, col3 = st.columns(3)

    with col1:
        room_type = st.selectbox(
            "Room Type",
            ["Entire home/apt", "Private room", "Shared room"]
        )
        property_type = st.selectbox(
            "Property Type",
            ["Apartment", "House", "Condominium", "Townhouse", "Loft"]
        )
        neighbourhood = st.selectbox(
            "Neighbourhood Group",
            ["Manhattan", "Brooklyn", "Queens", "Bronx", "Staten Island"]
        )
        accommodates = st.number_input(
            "Accommodates", min_value=1, max_value=16, value=2
        )
        bedrooms = st.number_input(
            "Bedrooms", min_value=0.0, max_value=10.0, value=1.0
        )
        beds = st.number_input(
            "Beds", min_value=1.0, max_value=18.0, value=1.0
        )

    with col2:
        bathrooms = st.number_input(
            "Bathrooms", min_value=0.5, max_value=10.0, value=1.0
        )
        guests_included = st.number_input(
            "Guests Included", min_value=1, value=1
        )
        minimum_nights = st.number_input(
            "Minimum Nights", min_value=1, value=2
        )
        maximum_nights = st.number_input(
            "Maximum Nights", min_value=1, value=30
        )
        number_of_reviews = st.number_input(
            "Number of Reviews", min_value=0, value=10
        )
        review_scores_rating = st.number_input(
            "Review Score Rating", min_value=0.0,
            max_value=100.0, value=95.0
        )

    with col3:
        reviews_per_month = st.number_input(
            "Reviews Per Month", min_value=0.0, value=1.5
        )
        host_listings_count = st.number_input(
            "Calculated Host Listings Count", min_value=1, value=1
        )
        instant_bookable = st.selectbox(
            "Instant Bookable", [True, False],
            format_func=lambda x: "Yes" if x else "No"
        )
        host_is_superhost = st.selectbox(
            "Host Is Superhost", [True, False],
            format_func=lambda x: "Yes" if x else "No"
        )

    submitted = st.form_submit_button(
        "✨ Predict Price", use_container_width=True
    )

if submitted:
    # Feature names and order must match the training notebook
    listing = pd.DataFrame([{
        "room_type": room_type,
        "property_type": property_type,
        "neighbourhood_group_cleansed": neighbourhood,
        "accommodates": accommodates,
        "bedrooms": bedrooms,
        "beds": beds,
        "bathrooms": bathrooms,
        "guests_included": guests_included,
        "minimum_nights": minimum_nights,
        "maximum_nights": maximum_nights,
        "number_of_reviews": number_of_reviews,
        "review_scores_rating": review_scores_rating,
        "reviews_per_month": reviews_per_month,
        "calculated_host_listings_count": host_listings_count,
        "instant_bookable": instant_bookable,
        "host_is_superhost": host_is_superhost
    }])

    try:
        prediction = model.predict(listing)[0]

        st.success("Price prediction generated successfully!")
        st.metric(label="💰 Estimated Price per Night",value=f"${prediction:,.2f}")

        st.caption(
            "🏠 This price is an estimate generated by the Random Forest model."
        )
        st.caption(
            "This is a model estimate, not a guaranteed market price. "
            "The currency and pricing period follow the source dataset."
        )

        with st.expander("View submitted listing details"):
            st.dataframe(listing, use_container_width=True)

    except Exception as error:
        st.error(f"Prediction failed: {error}")

st.divider()

# Model comparison
st.header("📊 Model Performance")

results = pd.DataFrame({
    "Model": ["Linear Regression", "Random Forest"],
    "MAE": [56.41, 50.34],
    "RMSE": [104.20, 97.99],
    "R² Score": [0.4026, 0.4717]
})

st.dataframe(results, use_container_width=True)

chart_col1, chart_col2 = st.columns(2)

with chart_col1:
    st.subheader("MAE Comparison")
    st.bar_chart(results.set_index("Model")[["MAE"]])

with chart_col2:
    st.subheader("R² Score Comparison")
    st.bar_chart(results.set_index("Model")[["R² Score"]])

st.info(
    "Random Forest performed better than Linear Regression "
    "on all three evaluation metrics in the selected test split."
)

st.caption("Airbnb Listing Price Analyzer | Data Science Project")
